#!/usr/bin/env node
/**
 * Generates the tray icon as a macOS "template" image: black pixels plus alpha,
 * which the OS tints for light and dark menu bars.
 *
 * The result is written both to resources/ (for reference) and to
 * src/main/trayIcon.ts as base64, and the app loads the base64 one. Embedding it
 * avoids resolving a resource path at runtime, which differs between `dev` and a
 * packaged build and is a reliable source of a tray with no icon in it.
 *
 * Run: node scripts/make-tray-icon.mjs
 */
import { deflateSync } from 'node:zlib'
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const S = 32 // drawn at 2x so the 16pt tray slot gets a retina asset

/** Coverage of a disc at a pixel centre, sampled 3x3 for a cheap anti-alias. */
function disc(x, y, cx, cy, r) {
  let hits = 0
  for (let sy = 0; sy < 3; sy++) {
    for (let sx = 0; sx < 3; sx++) {
      const px = x + (sx + 0.5) / 3
      const py = y + (sy + 0.5) / 3
      if ((px - cx) ** 2 + (py - cy) ** 2 <= r * r) hits++
    }
  }
  return hits / 9
}

/** Coverage of a triangle, same sampling. */
function tri(x, y, ax, ay, bx, by, cx2, cy2) {
  const sign = (px, py, qx, qy, rx, ry) => (px - rx) * (qy - ry) - (qx - rx) * (py - ry)
  let hits = 0
  for (let sy = 0; sy < 3; sy++) {
    for (let sx = 0; sx < 3; sx++) {
      const px = x + (sx + 0.5) / 3
      const py = y + (sy + 0.5) / 3
      const d1 = sign(px, py, ax, ay, bx, by)
      const d2 = sign(px, py, bx, by, cx2, cy2)
      const d3 = sign(px, py, cx2, cy2, ax, ay)
      const neg = d1 < 0 || d2 < 0 || d3 < 0
      const pos = d1 > 0 || d2 > 0 || d3 > 0
      if (!(neg && pos)) hits++
    }
  }
  return hits / 9
}

// A cat head: one disc, two ears, two punched-out eyes.
const px = new Uint8Array(S * S * 4)
for (let y = 0; y < S; y++) {
  for (let x = 0; x < S; x++) {
    let a = disc(x, y, 16, 19, 10.5)
    a = Math.max(a, tri(x, y, 6.5, 13, 9, 3, 14.5, 10))
    a = Math.max(a, tri(x, y, 25.5, 13, 23, 3, 17.5, 10))
    // Eyes, cut out so the shape still reads as a face at 16px.
    a *= 1 - disc(x, y, 12, 18, 2.1)
    a *= 1 - disc(x, y, 20, 18, 2.1)
    const i = (y * S + x) * 4
    px[i] = 0
    px[i + 1] = 0
    px[i + 2] = 0
    px[i + 3] = Math.round(Math.max(0, Math.min(1, a)) * 255)
  }
}

function chunk(type, data) {
  const len = Buffer.alloc(4)
  len.writeUInt32BE(data.length)
  const body = Buffer.concat([Buffer.from(type, 'latin1'), data])
  const crcTable = (chunk.table ??= (() => {
    const t = new Int32Array(256)
    for (let n = 0; n < 256; n++) {
      let c = n
      for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1
      t[n] = c
    }
    return t
  })())
  let crc = -1
  for (const b of body) crc = crcTable[(crc ^ b) & 0xff] ^ (crc >>> 8)
  const crcBuf = Buffer.alloc(4)
  crcBuf.writeInt32BE(crc ^ -1)
  return Buffer.concat([len, body, crcBuf])
}

const ihdr = Buffer.alloc(13)
ihdr.writeUInt32BE(S, 0)
ihdr.writeUInt32BE(S, 4)
ihdr[8] = 8 // bit depth
ihdr[9] = 6 // RGBA
const raw = Buffer.alloc(S * (S * 4 + 1))
for (let y = 0; y < S; y++) {
  raw[y * (S * 4 + 1)] = 0 // filter: none
  Buffer.from(px.buffer, y * S * 4, S * 4).copy(raw, y * (S * 4 + 1) + 1)
}
const png = Buffer.concat([
  Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
  chunk('IHDR', ihdr),
  chunk('IDAT', deflateSync(raw, { level: 9 })),
  chunk('IEND', Buffer.alloc(0))
])

writeFileSync(join(root, 'resources', 'trayTemplate.png'), png)
writeFileSync(
  join(root, 'src', 'main', 'trayIcon.ts'),
  `// Generated by scripts/make-tray-icon.mjs — do not edit by hand.\n` +
    `export const TRAY_ICON_PNG_BASE64 =\n  '${png.toString('base64')}'\n`
)
console.log(`wrote ${png.length} byte icon`)
